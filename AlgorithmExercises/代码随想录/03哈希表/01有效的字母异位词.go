package main

import "fmt"

// isAnagram 判断字符串 t 是否是字符串 s 的字母异位词
// 字母异位词指字母相同，但排列顺序不同的字符串
func isAnagram(s string, t string) bool {
	// 如果两个字符串的长度都不相等，那它们绝对不可能是字母异位词
	if len(s) != len(t) {
		return false
	}

	// 题目说明只包含小写字母，所以可以用一个长度为 26 的数组来记录每个字母出现的次数
	// record 数组用来记录每个字母在 s 中出现的次数与在 t 中出现次数的差值
	record := make([]int, 26)

	// 遍历字符串 s，将 s 中的字母在 record 中对应的位置加 1
	for _, char := range s {
		// char 是 rune 类型，减去 'a' 就能得到 0-25 之间的索引
		record[char-'a']++
	}

	// 遍历字符串 t，将 t 中的字母在 record 中对应的位置减 1
	for _, char := range t {
		record[char-'a']--
	}

	// 遍历 record 数组，如果所有元素都为 0，说明 s 和 t 包含的字母种类和数量完全相同
	// 如果有任何一个元素不为 0，说明它们不是字母异位词
	for _, count := range record {
		if count != 0 {
			return false
		}
	}

	// 全部为 0，返回 true
	return true
}

func main() {
	// 示例 1
	s1, t1 := "anagram", "nagaram"
	fmt.Printf("输入: s = \"%s\", t = \"%s\"\n", s1, t1)
	fmt.Printf("输出: %t\n\n", isAnagram(s1, t1))

	// 示例 2
	s2, t2 := "rat", "car"
	fmt.Printf("输入: s = \"%s\", t = \"%s\"\n", s2, t2)
	fmt.Printf("输出: %t\n", isAnagram(s2, t2))
}

